pub fn sequential_digits(low: i32, high: i32) -> Vec<i32> {
    let candidates = [
        12, 23, 34, 45, 56, 67, 78, 89, 123, 234, 345, 456, 567, 678, 789, 1234, 2345, 3456, 4567,
        5678, 6789, 12345, 23456, 34567, 45678, 56789, 123456, 234567, 345678, 456789, 1234567,
        2345678, 3456789, 12345678, 23456789, 123456789,
    ];
    candidates
        .into_iter()
        .filter(|&c| c >= low && c <= high)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_sequential_digits() {
        assert_eq!(vec![123, 234], sequential_digits(100, 300));
        assert_eq!(
            vec![1234, 2345, 3456, 4567, 5678, 6789, 12345],
            sequential_digits(1000, 13000)
        );
        assert_eq!(
            vec![
                12, 23, 34, 45, 56, 67, 78, 89, 123, 234, 345, 456, 567, 678, 789, 1234, 2345,
                3456, 4567, 5678, 6789, 12345, 23456, 34567, 45678, 56789, 123456, 234567, 345678,
                456789, 1234567, 2345678, 3456789, 12345678, 23456789, 123456789
            ],
            sequential_digits(10, 1000000000)
        );
    }
}
